"""Wake interactive harnesses when their Orchestra work needs attention."""
from __future__ import annotations

import json
import os
import re
import shlex
import time
from pathlib import Path

from orchestra_cli import config, db, reap


_RUN_DELIVERY_KINDS = ("interrupt", "checkin", "queued")
_HOOK_TIMEOUT_SECONDS = 36000

_SESSION_RE = re.compile(r"^[A-Za-z0-9._:-]{1,256}$")

_CODEX_STOP_HANDLER = {
    "type": "command",
    "command": "orchestra hook --backend codex",
    "timeout": _HOOK_TIMEOUT_SECONDS,
    "statusMessage": "Waiting for Orchestra workers",
}
_CLAUDE_STOP_HANDLER = {
    "type": "command",
    "command": "orchestra hook --backend claude",
    "timeout": _HOOK_TIMEOUT_SECONDS,
    "statusMessage": "Waiting for Orchestra workers",
}
_CODEX_START_HANDLER = {
    "type": "command",
    "command": "orchestra hook --backend codex --bind",
    "timeout": 10,
}
_CLAUDE_START_HANDLER = {
    "type": "command",
    "command": "orchestra hook --backend claude --bind",
    "timeout": 10,
}

_OPENCODE_PLUGIN = """\
// Generated by `orchestra hooks install`. Safe for Orchestra to replace.
export const OrchestraPlugin = async ({ client, $, directory }) => {
  const waiting = new Set()
  return {
    "shell.env": async (input, output) => {
      if (!process.env.ORCHESTRA_RUN_ID && input.sessionID) {
        output.env.ORCHESTRA_HARNESS_SESSION = input.sessionID
      }
    },
    event: async ({ event }) => {
      if (event.type !== "session.idle") return
      const sessionID = event.properties.sessionID
      if (waiting.has(sessionID)) return
      waiting.add(sessionID)
      try {
        const prompt = (await $`orchestra hook --backend opencode --session ${sessionID}`.nothrow().text()).trim()
        if (!prompt) return
        await client.session.promptAsync({
          path: { id: sessionID },
          query: { directory },
          body: { parts: [{ type: "text", text: prompt }] },
        })
      } finally {
        waiting.delete(sessionID)
      }
    },
  }
}

export default OrchestraPlugin
"""


def valid_session_id(value: object) -> str | None:
    """Accept only the bounded, shell-safe session identifiers used by harnesses."""
    if isinstance(value, str) and _SESSION_RE.fullmatch(value):
        return value
    return None


def bind_session(backend: str, session_id: str, env_file: str | None = None) -> str:
    """Bind commands from an interactive harness to its durable session."""
    if os.environ.get("ORCHESTRA_RUN_ID"):
        return ""
    session_id = valid_session_id(session_id) or ""
    if not session_id:
        return ""
    if backend == "claude" and env_file:
        try:
            with Path(env_file).open("a", encoding="utf-8") as handle:
                handle.write(
                    f"export ORCHESTRA_HARNESS_SESSION={shlex.quote(session_id)}\n"
                )
        except OSError:
            return ""
    return (
        "This interactive harness is bound to Orchestra session "
        f"{session_id}. When invoking `orchestra dispatch`, include "
        f"`--harness-session {session_id}` unless "
        "ORCHESTRA_HARNESS_SESSION is already set. Do not reuse this session ID "
        "in another harness conversation."
    )


def _active_owned_runs(
    con, recipient: str, current_run_id: int | None, session_id: str
) -> list[int]:
    query = (
        "SELECT id FROM runs WHERE requested_by=? "
        "AND harness_session=? "
        "AND status NOT IN ('done','failed','timeout','killed')"
    )
    params: list[object] = [recipient, session_id]
    if current_run_id is not None:
        query += " AND id != ?"
        params.append(current_run_id)
    return [int(row["id"]) for row in con.execute(query + " ORDER BY id", params)]


def _claim_messages(con, recipient: str, session_id: str):
    """Claim harness mail without stealing supervisor-owned runner delivery."""
    placeholders = ",".join("?" for _ in _RUN_DELIVERY_KINDS)
    query = (
        "SELECT messages.* FROM messages JOIN runs ON runs.id=messages.run_id "
        "WHERE messages.recipient=? AND runs.harness_session=? "
        "AND messages.read_at IS NULL AND messages.recalled_at IS NULL "
        f"AND COALESCE(kind,'') NOT IN ({placeholders}) "
        "ORDER BY messages.id LIMIT 20"
    )
    params = (recipient, session_id, *_RUN_DELIVERY_KINDS)
    con.execute("BEGIN IMMEDIATE")
    rows = list(con.execute(query, params))
    if rows:
        ids = ",".join(str(int(row["id"])) for row in rows)
        con.execute(
            f"UPDATE messages SET read_at=? WHERE id IN ({ids}) AND read_at IS NULL",
            (db.now(),),
        )
    con.execute("COMMIT")
    return rows


def wait_for_attention(
    root: Path, session_id: str, *, poll_interval: float = 0.25
) -> str | None:
    """Wait while this harness owns live runs, returning the next durable event."""
    session_id = valid_session_id(session_id) or ""
    if not session_id:
        return None
    cfg = config.load(root)
    recipient = os.environ.get("ORCHESTRA_SELF") or cfg["settings"].get(
        "default_requester", "orchestrator"
    )
    try:
        current_run_id = int(os.environ["ORCHESTRA_RUN_ID"])
    except (KeyError, ValueError):
        current_run_id = None

    con = db.connect(root)
    try:
        next_reap_at = 0.0
        while True:
            now = time.monotonic()
            if now >= next_reap_at:
                reap.reap_orphans(con, root)
                next_reap_at = now + 5
            messages = _claim_messages(con, recipient, session_id)
            if messages:
                rendered = "\n\n".join(
                    f"[message {row['id']} from {row['sender']}]\n{row['body']}"
                    for row in messages
                )
                return (
                    "Orchestra received the following event(s) while you were waiting. "
                    "Handle them now: answer blocking questions, send guidance for "
                    "consultations, and verify completed work before accepting it.\n\n"
                    f"{rendered}"
                )
            if not _active_owned_runs(con, recipient, current_run_id, session_id):
                return None
            time.sleep(poll_interval)
    finally:
        con.close()


def render_hook_result(backend: str, prompt: str | None) -> str:
    if backend == "opencode":
        return prompt or ""
    if prompt:
        return json.dumps({"decision": "block", "reason": prompt})
    return "{}"


def _install_hook(path: Path, event: str, handler: dict) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, ValueError) as exc:
            raise RuntimeError(f"cannot merge harness hook into {path}: {exc}") from exc
        if not isinstance(data, dict):
            raise RuntimeError(f"cannot merge harness hook into {path}: root must be an object")
    else:
        data = {}
    hooks = data.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise RuntimeError(f"cannot merge harness hook into {path}: hooks must be an object")
    groups = hooks.setdefault(event, [])
    if not isinstance(groups, list):
        raise RuntimeError(
            f"cannot merge harness hook into {path}: hooks.{event} must be a list"
        )
    if any(
        isinstance(group, dict)
        and any(
            isinstance(item, dict) and item.get("command") == handler["command"]
            for item in group.get("hooks", [])
        )
        for group in groups
    ):
        return "already present"
    groups.append({"hooks": [handler]})
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return "installed"


def install_global() -> list[str]:
    """Install once for every project used by this OS account."""
    codex_home = Path(os.environ.get("CODEX_HOME", "~/.codex")).expanduser()
    claude_home = Path(os.environ.get("CLAUDE_CONFIG_DIR", "~/.claude")).expanduser()
    xdg_config = Path(os.environ.get("XDG_CONFIG_HOME", "~/.config")).expanduser()
    statuses = [
        "Codex: " + ", ".join((
            "start " + _install_hook(
                codex_home / "hooks.json", "SessionStart", _CODEX_START_HANDLER
            ),
            "stop " + _install_hook(
                codex_home / "hooks.json", "Stop", _CODEX_STOP_HANDLER
            ),
        )),
        "Claude: " + ", ".join((
            "start " + _install_hook(
                claude_home / "settings.json", "SessionStart", _CLAUDE_START_HANDLER
            ),
            "stop " + _install_hook(
                claude_home / "settings.json", "Stop", _CLAUDE_STOP_HANDLER
            ),
        )),
    ]
    plugin = xdg_config / "opencode" / "plugins" / "orchestra.js"
    plugin.parent.mkdir(parents=True, exist_ok=True)
    if not plugin.exists():
        plugin.write_text(_OPENCODE_PLUGIN, encoding="utf-8")
        status = "installed"
    elif plugin.read_text(encoding="utf-8") == _OPENCODE_PLUGIN:
        status = "already present"
    elif plugin.read_text(encoding="utf-8").startswith(
        ("// Generated by `orchestra init`.", "// Generated by `orchestra hooks install`.")
    ):
        plugin.write_text(_OPENCODE_PLUGIN, encoding="utf-8")
        status = "updated"
    else:
        status = f"preserved conflicting {plugin}"
    statuses.append(f"OpenCode: {status}")
    return statuses
